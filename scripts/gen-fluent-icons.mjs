// Builds src/components/fluentIcons.ts from Microsoft's open-source Fluent UI
// System Icons (MIT licence, https://github.com/microsoft/fluentui-system-icons).
// Run:  npm pack @fluentui/svg-icons && tar xzf fluentui-svg-icons-*.tgz
//       node scripts/gen-fluent-icons.mjs package/icons
// Only the handful of glyphs the app uses are kept, so the bundle stays tiny.

import { readFileSync, writeFileSync, existsSync } from "node:fs";

const dir = process.argv[2] ?? "package/icons";
const MAP = {
  back: "arrow_left", forward: "arrow_right", up: "arrow_up", refresh: "arrow_clockwise", clock: "clock",
  search: "search", settings: "settings", close: "dismiss", plus: "add", home: "home", pc: "desktop",
  pin: "pin", terminal: "window_console", details: "panel_right", grid: "grid", list: "text_bullet_list",
  chart: "data_pie", pause: "pause", play: "play", trash: "delete", chevron: "chevron_right",
  drive: "hard_drive", network: "globe", copy: "copy", cut: "cut", paste: "clipboard_paste",
  rename: "rename", share: "share", newItem: "add", sort: "arrow_sort", view: "apps_list",
  filter: "filter", more: "more_horizontal", undo: "arrow_undo", archive: "archive", redo: "arrow_redo",
  check: "checkmark", sidebar: "panel_left", star: "star", minimize: "subtract", maximize: "square",
  restore: "square_multiple", popin: "arrow_minimize", popout: "open", expand: "chevron_down",
  collapse: "chevron_up", info: "info", folderOpen: "folder_open", shield: "shield", lock: "lock_closed",
  cpu: "developer_board", profile: "person", preset: "options", memory: "memory", eject: "arrow_download",
};

const out = {};
const missing = [];
for (const [ours, theirs] of Object.entries(MAP)) {
  let done = false;
  for (const size of [16, 20, 24]) {
    const file = `${dir}/${theirs}_${size}_regular.svg`;
    if (!existsSync(file)) continue;
    const svg = readFileSync(file, "utf8");
    const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
    if (!paths.length) continue;
    out[ours] = { s: size, d: paths };
    done = true;
    break;
  }
  if (!done) missing.push(`${ours} (${theirs})`);
}
const body = `// Generated by scripts/gen-fluent-icons.mjs from Fluent UI System Icons
// (Copyright (c) Microsoft Corporation, MIT licence). Do not edit by hand.
// These are open-source icons drawn in the same style as Windows 11; they are
// not Windows' own icon files.

export const FLUENT: Record<string, { s: number; d: string[] }> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync("src/components/fluentIcons.ts", body);
console.log(`wrote ${Object.keys(out).length} icons; missing: ${missing.join(", ") || "none"}`);
